#!/usr/bin/env node
// Builds apps-script/core/Generated.js from the single sources of truth:
//   tools/ops-tools.json, tools/output-schemas.json, prompts/*.md, sql/01_views.sql
// Apps Script can't read repo files at runtime, so these get embedded as globals.
// A test fails if Generated.js is out of date. Run: npm run build
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const GENERATED_PATH = join(ROOT, 'apps-script', 'core', 'Generated.js');

export function buildGenerated() {
  const tools = JSON.parse(readFileSync(join(ROOT, 'tools', 'ops-tools.json'), 'utf8'));
  const outputs = JSON.parse(readFileSync(join(ROOT, 'tools', 'output-schemas.json'), 'utf8'));
  const prompts = {};
  for (const f of readdirSync(join(ROOT, 'prompts')).filter((f) => f.endsWith('.md')).sort()) {
    prompts[f.replace(/\.md$/, '')] = readFileSync(join(ROOT, 'prompts', f), 'utf8').trim();
  }
  return [
    '// GENERATED by lib/build-generated.mjs. Do not edit; edit tools/*.json and prompts/*.md, then npm run build.',
    '// DEMO DATA project (fictional brand).',
    'var OPS_TOOL_SCHEMAS = ' + JSON.stringify(tools, null, 2) + ';',
    'var OPS_OUTPUT_SCHEMAS = ' + JSON.stringify(outputs, null, 2) + ';',
    'var OPS_PROMPTS = ' + JSON.stringify(prompts, null, 2) + ';',
    'var OPS_BQ_VIEWS_SQL = ' + JSON.stringify(readFileSync(join(ROOT, 'sql', '01_views.sql'), 'utf8')) + ';',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(GENERATED_PATH, buildGenerated());
  console.log('Wrote', GENERATED_PATH);
}
